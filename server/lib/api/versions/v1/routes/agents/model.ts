import { z } from "zod";
import { AgentSettings, FirmwareSettings } from "../../../../utils/shared-models/netigniteData";

export namespace AgentsModel {
	export const Name = z.string().trim().min(1, "Name is required").max(64, "Name is too long");
	export const Description = z.string().trim().max(500, "Description is too long");

	export const Agent = z.object({
		id: z.number(),
		name: z.string(),
		description: z.string(),
		kind: AgentSettings.Kind,
		state: AgentSettings.ConnectionState,
		version: z.string().nullable(),
		capabilities: z.array(z.string()),
		info: z.record(z.string(), z.unknown()).nullable(),
		last_seen_at: z.number().nullable(),
		enrolled_at: z.number().nullable(),
		created_at: z.number(),
	});
	export type Agent = z.infer<typeof Agent>;
}

export namespace AgentsModel.Create {
	export const Body = z.object({
		name: AgentsModel.Name,
		description: AgentsModel.Description.default(""),
		kind: AgentSettings.Kind,
	});
	export type Body = z.infer<typeof Body>;
}

export namespace AgentsModel.Update {
	export const Body = z.object({
		name: AgentsModel.Name.optional(),
		description: AgentsModel.Description.optional(),
	});
	export type Body = z.infer<typeof Body>;
}

export namespace AgentsModel.Enrollment {
	export const Response = z.object({
		/** Single-use, valid for 15 minutes. */
		token: z.string(),
		expires_at: z.number(),
	});
	export type Response = z.infer<typeof Response>;
}

export namespace AgentsModel.Enroll {
	export const Body = z.object({
		enrollment_token: z.string().min(1).max(256),
		/** Generated by the agent: 32–128 characters `A-Z a-z 0-9 _ -`. */
		secret: z.string().min(32).max(128),
	});
	export type Body = z.infer<typeof Body>;

	export const Response = z.object({
		agent_id: z.number(),
		kind: AgentSettings.Kind,
		/** The agent connects with `Authorization: Bearer netignite_agent_<token_id>:<secret>`. */
		token_id: z.string(),
	});
	export type Response = z.infer<typeof Response>;
}

export namespace AgentsModel.FlashImage {
	export const Body = z.object({
		/** Firmware release the image is for (its NVS layout). */
		version: FirmwareSettings.Version,
		/** URL the agent connects to. Defaults to the server's public URL (NETIGNITE_APP_URL). */
		server_url: z
			.url({ protocol: /^https?$/, error: "Must be an http:// or https:// URL" })
			.max(200)
			.refine((url) => {
				const parsed = new URL(url);
				return !parsed.username && !parsed.password && !parsed.search && !parsed.hash;
			}, "The URL can't contain credentials, a query or a fragment")
			.optional(),
	});
	export type Body = z.infer<typeof Body>;

	export const Response = z.object({
		/** NVS partition image (base64) with the server URL, the agent's name and a single-use enrollment token. */
		image: z.string(),
		/** Flash offset of the image. */
		offset: z.number(),
		server_url: z.string(),
		/** The enrollment token in the image expires at this time; flash before. */
		expires_at: z.number(),
	});
	export type Response = z.infer<typeof Response>;
}
