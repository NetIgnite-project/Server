import { z } from "zod";
import { AgentSettings, FirmwareSettings } from "../../../../utils/shared-models/netigniteData";

export namespace AgentsModel {
	export const Name = z.string().trim().min(1, "Name is required").max(64, "Name is too long");
	export const Description = z.string().trim().max(500, "Description is too long");

	/** An OTA update of an ESP32 agent (kept in memory; see OtaService). */
	export const FirmwareUpdate = z.object({
		version: z.string(),
		from_version: z.string().nullable(),
		state: z.enum(["queued", "starting", "downloading", "restarting", "done", "failed"]),
		percent: z.number(),
		error: z.string().nullable(),
		started_at: z.number(),
		updated_at: z.number(),
	});
	export type FirmwareUpdate = z.infer<typeof FirmwareUpdate>;

	export const Agent = z.object({
		id: z.number(),
		name: z.string(),
		description: z.string(),
		kind: AgentSettings.Kind,
		state: AgentSettings.ConnectionState,
		version: z.string().nullable(),
		capabilities: z.array(z.string()),
		info: z.record(z.string(), z.unknown()).nullable(),
		last_seen_at: z.number().nullable(),
		enrolled_at: z.number().nullable(),
		created_at: z.number(),
		/** The current or last firmware update (ESP32). */
		update: FirmwareUpdate.nullable(),
		/** A newer firmware of the admin's channel, if the agent can be updated to it. */
		update_available: z.string().nullable(),
	});
	export type Agent = z.infer<typeof Agent>;
}

export namespace AgentsModel.Create {
	export const Body = z.object({
		name: AgentsModel.Name,
		description: AgentsModel.Description.default(""),
		kind: AgentSettings.Kind,
	});
	export type Body = z.infer<typeof Body>;
}

export namespace AgentsModel.Update {
	export const Body = z.object({
		name: AgentsModel.Name.optional(),
		description: AgentsModel.Description.optional(),
	});
	export type Body = z.infer<typeof Body>;
}

export namespace AgentsModel.Enrollment {
	export const Response = z.object({
		/** Single-use, valid for 15 minutes. */
		token: z.string(),
		expires_at: z.number(),
	});
	export type Response = z.infer<typeof Response>;
}

export namespace AgentsModel.Enroll {
	export const Body = z.object({
		enrollment_token: z.string().min(1).max(256),
		/** Generated by the agent: 32–128 characters `A-Z a-z 0-9 _ -`. */
		secret: z.string().min(32).max(128),
		/** The enrolling agent's kind. A token of another kind is refused before it is used. */
		kind: AgentSettings.Kind.optional(),
	});
	export type Body = z.infer<typeof Body>;

	export const Response = z.object({
		agent_id: z.number(),
		kind: AgentSettings.Kind,
		/** The agent connects with `Authorization: Bearer netignite_agent_<token_id>:<secret>`. */
		token_id: z.string(),
	});
	export type Response = z.infer<typeof Response>;
}

export namespace AgentsModel.FlashImage {
	export const Body = z.object({
		/** Firmware release the image is for (its NVS layout). */
		version: FirmwareSettings.Version,
		/** URL the agent connects to. Defaults to the server's public URL (NETIGNITE_APP_URL). */
		server_url: z
			.url({ protocol: /^https?$/, error: "Must be an http:// or https:// URL" })
			.max(200)
			.refine((url) => {
				const parsed = new URL(url);
				return !parsed.username && !parsed.password && !parsed.search && !parsed.hash;
			}, "The URL can't contain credentials, a query or a fragment")
			.optional(),
	});
	export type Body = z.infer<typeof Body>;

	export const Response = z.object({
		/** NVS partition image (base64) with the server URL, the agent's name and a single-use enrollment token. */
		image: z.string(),
		/** Flash offset of the image. */
		offset: z.number(),
		server_url: z.string(),
		/** The enrollment token in the image expires at this time; flash before. */
		expires_at: z.number(),
	});
	export type Response = z.infer<typeof Response>;
}

export namespace AgentsModel.StartUpdate {
	export const Body = z.object({
		/** A synced firmware release; defaults to the recommended one. Older versions are allowed. */
		version: FirmwareSettings.Version.optional(),
	});
	export type Body = z.infer<typeof Body>;
}

export namespace AgentsModel.BulkUpdate {
	export const Body = z.object({
		agent_ids: z.array(z.number().int().positive()).min(1).max(200),
		/** Defaults to the recommended release. */
		version: FirmwareSettings.Version.optional(),
	});
	export type Body = z.infer<typeof Body>;

	export const Response = z.object({
		version: z.string(),
		/** Updated one after another, in this order. */
		queued: z.array(z.number()),
		skipped: z.array(z.object({ agent_id: z.number(), reason: z.string() })),
	});
	export type Response = z.infer<typeof Response>;
}

export namespace AgentsModel.Logs {
	export const Response = z.object({
		/** The agent's most recent log lines (about 16 KB), oldest first. */
		lines: z.array(z.string()),
		level: z.enum(["error", "warn", "info", "debug"]).nullable(),
	});
	export type Response = z.infer<typeof Response>;
}

export namespace AgentsModel.Info {
	export const Response = z.object({
		version: z.string().nullable(),
		info: z.record(z.string(), z.unknown()),
	});
	export type Response = z.infer<typeof Response>;
}

export namespace AgentsModel.DeviceConfig {
	const IPv4 = z.ipv4({ error: "Must be an IPv4 address" });

	export const Body = z
		.object({
			/**
			 * Where the agent connects. The agent tries it and keeps it only if it reaches the server
			 * with it within 2 minutes; otherwise it restarts with the previous address.
			 */
			server_url: z
				.url({ protocol: /^https?$/, error: "Must be an http:// or https:// URL" })
				.max(200)
				.refine((url) => {
					const parsed = new URL(url);
					return !parsed.username && !parsed.password && !parsed.search && !parsed.hash;
				}, "The URL can't contain credentials, a query or a fragment")
				.optional(),
			/** The agent's network host name (after its next restart). */
			name: z
				.string()
				.regex(/^[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?$/, "Letters, digits and -, max. 63")
				.optional(),
			log_level: z.enum(["error", "warn", "info", "debug"]).optional(),
			/** DHCP or a static IPv4 configuration; tried like `server_url`. */
			ip: z
				.discriminatedUnion("mode", [
					z.object({ mode: z.literal("dhcp") }),
					z.object({
						mode: z.literal("static"),
						address: IPv4,
						gateway: IPv4,
						netmask: IPv4,
						dns1: IPv4.optional(),
						dns2: IPv4.optional(),
					}),
				])
				.optional(),
		})
		.refine((body) => Object.values(body).some((value) => value !== undefined), "Nothing to change");
	export type Body = z.infer<typeof Body>;
}
